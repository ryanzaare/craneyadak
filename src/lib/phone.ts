// شماره‌ی واتساپ برای wa.me. ⚠️ wa.me فقط قالب بین‌المللی بدون صفر و بدون + می‌پذیرد
// (`989121234567`). سایت زنده «09129430495» را عیناً می‌ساخت (`wa.me/09129430495`) و واتساپ
// آن را «شماره‌ی نامعتبر» می‌خواند — لینک واتساپ همه‌ی صفحه‌ها خراب بود.
// ارقام فارسی/عربی هم (پنل فارسی‌نویس) به لاتین تبدیل می‌شوند.
// ---------------------------------------------------------------------------

const toLatin = (s: string) =>
  s.replace(/[۰-۹٠-٩]/g, (c) => String(c.charCodeAt(0) >= 0x06f0 ? c.charCodeAt(0) - 0x06f0 : c.charCodeAt(0) - 0x0660));

/** رقم‌های بین‌المللی برای wa.me، یا null اگر شماره‌ی ایرانی معتبری نیست. */
export function whatsappDigits(raw: string | null | undefined): string | null {
  if (!raw) return null;
  let d = toLatin(String(raw)).replace(/[^0-9]/g, '');
  if (d.startsWith('00')) d = d.slice(2);
  if (/^98\d{10}$/.test(d)) return d; // 989121234567
  if (/^0?9\d{9}$/.test(d)) return `98${d.replace(/^0/, '')}`; // 09121234567 یا 9121234567
  return null; // ثابت (021…) یا غیرایرانی: wa.me ندارد؛ لینک ساخته نشود
}
