// ضمانت هر دسته — متن *به دسته وابسته است* (کارفرما، ۱۹ مهر ۱۴۰۵). فقط دسته‌ای که کارفرما متنش را داده اینجا
// می‌آید؛ برای بقیه هیچ مدت یا شرطی نمایش داده نمی‌شود (قاعده‌ی ۲: هرگز از خودت نساز).
// ضمانت = «تعمیر»، نه تعویض یا بازگشت وجه.
//
// افزودن دسته‌ی تازه: یک ورودی با اسلاگِ دقیق دسته در `taxonomy`؛ آزمون `warranty.test.mts` اسلاگ ناموجود را می‌گیرد.
// ---------------------------------------------------------------------------

export interface CategoryWarranty {
  /** یک جمله‌ی روشن: چه چیزی، چند ماه. */
  headline: string;
  /** مواردی که ضمانت شامل‌شان *نمی‌شود* — هر مورد یک عبارت کوتاه. */
  exclusions: readonly string[];
}

export const WARRANTY_BY_CATEGORY: Readonly<Record<string, CategoryWarranty>> = {
  // 🔶 ترجمه‌ی فارسی از متن انگلیسی کارفرما؛ پیش از انتشار عمومی کارفرما تأیید کند.
  'remote-control': {
    headline: 'همه‌ی ریموت‌های کنترل ۱۸ ماه ضمانت تعمیر دارند.',
    exclusions: [
      'آسیب ناشی از نفوذ آب',
      'ضربه‌ی فیزیکی',
      'نوسانات برق',
      'نصب نادرست',
      'دست‌کاری غیرمجاز در سیستم',
      'استفاده از باتری نامناسب (مثل باتری شارژی)',
    ],
  },
};

/** ضمانتِ اولین دسته‌ی محصول که متن دارد؛ وگرنه null (هیچ ادعایی نمایش داده نمی‌شود). */
export function warrantyFor(categorySlugs: readonly string[] | null | undefined): CategoryWarranty | null {
  for (const slug of categorySlugs ?? []) {
    const w = WARRANTY_BY_CATEGORY[slug];
    if (w) return w;
  }
  return null;
}
