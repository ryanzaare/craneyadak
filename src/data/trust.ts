export interface Author {
  slug: string;
  name: string;
  /** سمت — در اسکیمای Person به‌عنوان jobTitle می‌رود. */
  jobTitle: string;
  /** یک تا دو جمله. مبنای اعتبار نویسنده را توضیح می‌دهد، نه رزومه‌ی کامل. */
  bio: string;
  /** مدارک/تخصص‌ها — در اسکیما به‌عنوان knowsAbout. */
  expertise: string[];
  /**
   * تصویر نویسنده در `public/`. رشته‌ی خالی = هنوز عکس واقعی نداریم؛
   * کامپوننت به حروف اول نام برمی‌گردد و هرگز تصویر آدم دیگری نشان نمی‌دهد.
   */
  image: string;
  /** پروفایل‌های واقعی (لینکدین و…) — فقط لینک واقعی وارد sameAs می‌شود. */
  sameAs: string[];
  verified: boolean;
}

