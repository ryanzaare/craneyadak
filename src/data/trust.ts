//
// چرا همه‌چیز اینجاست: کارفرما باید بتواند اعداد، نام‌ها و لوگوها را عوض کند
// بدون آن‌که به قالب‌ها دست بزند. اگر این مقادیر در دوازده فایل پخش بودند،
// قطعاً یکی جا می‌ماند و یک ادعای ساختگی روی سایت زنده باقی می‌ماند.
//
// ═══════════════════════════════════════════════════════════════════════════
// خط قرمزی که این فایل اعمال می‌کند — و دلیلش
// ═══════════════════════════════════════════════════════════════════════════
// بین «متن تبلیغاتی روی صفحه» و «داده‌ی ساختاریافته برای گوگل» تفاوت حقوقی
// و فنی وجود دارد و این تفاوت عمدی در کد پیاده شده است:
//
//   • متن روی صفحه («۳۰ سال تجربه») یک ادعای بازاریابی است. جای‌گذار بودنش
//     تا پیش از انتشار مشکلی ایجاد نمی‌کند و کارفرما آن را با عدد واقعی
//     جایگزین می‌کند. این‌ها رندر می‌شوند تا چیدمان وزن روانی درست را بگیرد.
//
//   • همان عدد داخل JSON-LD یک ادعای ماشین‌خوان به گوگل است. `AggregateRating`
//     یا `foundingDate` جعلی نقض مستقیم سیاست داده‌ی ساختاریافته‌ی گوگل است و
//     جریمه‌ی دستی (manual action) دارد — دقیقاً همان چیزی که کل پروژه برای
//     دوری از آن تلاش کرده.
//
// بنابراین: هر آیتم با `verified: false` روی صفحه دیده می‌شود اما **هرگز**
// وارد JSON-LD نمی‌شود. با `verified: true` هر دو فعال می‌شوند.
// تابع `unverifiedTrustItems()` در زمان build همه‌ی موارد تاییدنشده را
// فهرست می‌کند تا هیچ‌کدام سهواً منتشر نشوند.
// ═══════════════════════════════════════════════════════════════════════════

