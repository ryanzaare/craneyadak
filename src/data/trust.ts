export interface UnverifiedItem {
  group: string;
  id: string;
  detail: string;
}

/**
 * فهرست هر ادعای تاییدنشده. `src/lib/storefront.ts` این را در زمان build
 * چاپ می‌کند تا هیچ جای‌گذاری بی‌سروصدا منتشر نشود.
 */
export function unverifiedTrustItems(): UnverifiedItem[] {
  const out: UnverifiedItem[] = [];

  for (const m of COMPANY_METRICS) {
    if (!m.verified) out.push({ group: 'سنجه‌های شرکت', id: m.id, detail: `${m.value} — ${m.label}` });
  }
  for (const b of TRUST_BADGES) {
    if (!b.verified) out.push({ group: 'نشان‌های اعتماد', id: b.id, detail: b.title });
  }
  for (const a of Object.values(AUTHORS)) {
    if (!a.verified) out.push({ group: 'نویسندگان', id: a.slug, detail: `${a.name} — ${a.jobTitle}` });
  }

  return out;
}

/**
 * اسکیمای Person برای نویسنده — **فقط** وقتی تایید شده باشد.
 *
 * برگرداندن `undefined` برای نویسنده‌ی تاییدنشده عمدی است: انتشار
 * `Person` با نام ساختگی یعنی گفتن یک دروغ ماشین‌خوان به گوگل. متن روی
 * صفحه رندر می‌شود (کارفرما چیدمان را می‌بیند)، اما داده‌ی ساختاریافته نه.
 */
export function authorJsonLd(author: Author, siteUrl: string): Record<string, unknown> | undefined {
  if (!author.verified) return undefined;

  const node: Record<string, unknown> = {
    '@type': 'Person',
    '@id': `${siteUrl}/#author-${author.slug}`,
    name: author.name,
    jobTitle: author.jobTitle,
    description: author.bio,
    knowsAbout: author.expertise,
    worksFor: { '@id': `${siteUrl}/#organization` },
  };

  if (author.image) node.image = `${siteUrl}${author.image}`;
  if (author.sameAs.length > 0) node.sameAs = author.sameAs;

  return node;
}
