// محتوای تخصصی هر دسته — لایه‌ی «چیزی که رتبه می‌گیرد».
//
// ساختار سیلو و اسکیما به‌تنهایی رتبه نمی‌آورند. صفحه‌ی دسته‌ای با دو
// پاراگراف، هرقدر هم تمیز، از رقیبی که ۱۲۰۰ کلمه‌ی واقعاً مفید دارد جلو
// نمی‌زند. این فایل همان محتواست: معیار انتخاب، نشانه‌های خرابی، جدول
// مقایسه، بازه‌ی بازرسی و پرسش‌های واقعی خریدار.
//
// ⚠️ سیستم «تایید داده» (مهم):
// بخشی از اعداد و سازگاری‌های این متن، دانش عمومی صنعت است و بخشی باید
// توسط کارفرما تایید شود. هر مقدار نیازمند تایید با `verify: true` علامت
// خورده است. این پرچم‌ها:
//   ۱) در حالت بازبینی (`CONTENT_REVIEW=1`) روی صفحه با نشان زرد دیده
//      می‌شوند تا کارفرما دقیقاً بداند کدام کلمه/عدد را باید اصلاح کند.
//   ۲) در هر بیلد، فهرست کاملشان در ترمینال چاپ می‌شود.
// بنابراین امکان ندارد یک عدد تاییدنشده بی‌سروصدا منتشر شود.
// ---------------------------------------------------------------------------

/** یک مقدار متنی که ممکن است نیاز به تایید کارفرما داشته باشد. */
export interface Claim {
  text: string;
  /** true یعنی این مقدار تخمین حرفه‌ای است و باید توسط کارفرما تایید شود. */
  verify?: boolean;
  /** توضیح داخلی برای کارفرما: دقیقاً چه چیزی باید بررسی شود. */
  note?: string;
}

export interface ContentTable {
  caption: string;
  intro?: string;
  headers: string[];
  rows: Claim[][];
}

export interface ContentSection {
  id: string;
  heading: string;
  paragraphs?: string[];
  bullets?: Claim[];
  table?: ContentTable;
  /** جعبه‌ی هشدار/نکته‌ی برجسته. */
  callout?: { tone: 'warning' | 'info'; title: string; body: string };
}

export interface CategoryContent {
  /** اسلاگ دسته در taxonomy.ts */
  slug: string;
  /** پاراگراف‌های ابتدایی — نیت اصلی جستجو در ۱۰۰ کلمه‌ی اول پاسخ داده شود. */
  intro: string[];
  sections: ContentSection[];
  faqs: { q: string; a: string; verify?: boolean }[];
  /** استانداردهای مرجع — سیگنال E-E-A-T واقعی. */
  standards?: { code: string; title: string }[];
}

const c = (text: string): Claim => ({ text });
/** مقدار نیازمند تایید کارفرما. */
const v = (text: string, note?: string): Claim => ({ text, verify: true, note });

