// پیشنهادهای جستجوی سریع زیر نوار جستجوی صفحه‌ی اصلی.
//
// ⚠️ چرا این فایل جدا وجود دارد — و چرا برچسبش «بیشترین جستجوها» نیست:
//
// نسخه‌ی قبلی صفحه‌ی اصلی سه لینک ثابت را زیر عنوان «بیشترین جستجوها» نشان
// می‌داد. هیچ‌کس آن‌ها را جستجو نکرده بود؛ دست‌نویس بودند. این دقیقاً همان
// نوع داده‌ی ساختگی است که در بقیه‌ی پروژه حذف شد (کد فنی جعلی، حجم فایل
// دستی، امتیاز نداشته) — فقط چون «آمار» به نظر می‌رسید، از چشم افتاده بود.
//
// چرا نمی‌توان آن را «هوشمند و مبتنی بر جستجوهای واقعی گوگل» کرد:
//   ۱. گوگل هیچ API عمومی برای «جستجوهای اخیر» ندارد؛ Google Trends هم API
//      رسمی ندارد و اسکرپ‌کردنش خلاف شرایط استفاده است.
//   ۲. حتی اگر بود، حجم جستجوی عبارت‌های صنعتی فارسی در ایران زیر آستانه‌ی
//      گزارش‌دهی Trends است و پاسخ خالی برمی‌گرداند.
//   ۳. سایت خروجی استاتیک دارد و در زمان اجرا هیچ درخواستی نمی‌زند.
//
// تنها منبع واقعی و مجاز: **Search Console** — یعنی کوئری‌هایی که کاربران
// واقعاً با آن‌ها به همین سایت رسیده‌اند. آن داده تا وقتی سایت منتشر نشده و
// ترافیک نگرفته وجود ندارد.
//
// بنابراین فعلاً: برچسب صادقانه («دسته‌های پرکاربرد») + مقصدهای واقعی از
// تاکسونومی. وقتی داده‌ی Search Console موجود شد، فقط `MANUAL_SUGGESTIONS`
// با فهرست واقعی جایگزین می‌شود — بدون تغییر در هیچ کامپوننتی.
// ---------------------------------------------------------------------------
import { findCategory, categoryPath } from './taxonomy';

export interface QuickSuggestion {
  label: string;
  href: string;
}

/**
 * وقتی داده‌ی واقعی Search Console در دسترس قرار گرفت، همین آرایه با
 * پرترافیک‌ترین کوئری‌های واقعی جایگزین می‌شود و آن‌گاه — و فقط آن‌گاه —
 * می‌توان برچسب را به «بیشترین جستجوها» تغییر داد.
 */
const MANUAL_SUGGESTIONS: QuickSuggestion[] = [];

/** اسلاگ دسته‌هایی که به‌عنوان میان‌بُر نمایش داده می‌شوند. */
const FEATURED_CATEGORY_SLUGS = [
  'remote-control',
  'busbar-power-line',
  'gearbox-motor',
  'crane-wheel',
  'brake-wheel-disc',
];

/** برچسب بخش — عمداً یک ادعای آماری نیست. */
export const QUICK_LINKS_LABEL = 'دسته‌های پرکاربرد:';

/**
 * پیشنهادهای میان‌بُر. اگر داده‌ی واقعی موجود باشد از آن استفاده می‌شود،
 * وگرنه از دسته‌های واقعی تاکسونومی — در هر دو حالت، مقصدها صفحات واقعی‌اند.
 */
export function getQuickSuggestions(): QuickSuggestion[] {
  if (MANUAL_SUGGESTIONS.length > 0) return MANUAL_SUGGESTIONS;

  return FEATURED_CATEGORY_SLUGS.map((slug) => {
    const category = findCategory(slug);
    // اسلاگ اشتباه نباید بی‌صدا یک لینک شکسته بسازد.
    if (!category) {
      throw new Error(
        `[popular-searches] دسته‌ی «${slug}» در تاکسونومی وجود ندارد. ` +
          `FEATURED_CATEGORY_SLUGS را با src/data/taxonomy.ts هماهنگ کنید.`
      );
    }
    return { label: category.name, href: categoryPath(category) };
  });
}
