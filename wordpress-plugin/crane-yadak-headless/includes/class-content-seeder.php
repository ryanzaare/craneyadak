function cyh_handle_seed_content() {
	if ( ! current_user_can( 'manage_options' ) || ! check_admin_referer( 'cyh_seed_content' ) ) {
		wp_die( 'دسترسی مجاز نیست.' );
	}

	$r = cyh_seed_category_content();

	$notice = sprintf(
		'%d دسته بارگذاری شد%s%s',
		count( $r['seeded'] ),
		$r['skipped'] ? sprintf( '، %d دسته از قبل محتوا داشت و رد شد', count( $r['skipped'] ) ) : '',
		$r['missing'] ? sprintf( '، %d دسته پیدا نشد: %s', count( $r['missing'] ), implode( '، ', $r['missing'] ) ) : ''
	);

	set_transient( 'cyh_seed_notice', $notice, 60 );
	wp_safe_redirect( wp_get_referer() ?: admin_url() );
	exit;
}
add_action( 'admin_post_cyh_seed_content', 'cyh_handle_seed_content' );

function cyh_seed_admin_notice() {
	$notice = get_transient( 'cyh_seed_notice' );
	if ( ! $notice ) {
		return;
	}
	delete_transient( 'cyh_seed_notice' );
	printf( '<div class="notice notice-success is-dismissible"><p><strong>پیش‌نویس محتوا:</strong> %s</p></div>', esc_html( $notice ) );
}
add_action( 'admin_notices', 'cyh_seed_admin_notice' );
