/**
 * نوشتن پیش‌نویس‌ها روی ترم‌ها. هرگز مقدار موجود را بازنویسی نمی‌کند.
 *
 * @return array{seeded: string[], skipped: string[], missing: string[]}
 */
function cyh_seed_category_content() {
	$result = [ 'seeded' => [], 'skipped' => [], 'missing' => [] ];

	if ( ! function_exists( 'update_field' ) || ! function_exists( 'get_field' ) ) {
		return $result;
	}

	foreach ( cyh_content_drafts() as $slug => $draft ) {
		$term = get_term_by( 'slug', $slug, 'crane_category' );

		if ( ! $term || is_wp_error( $term ) ) {
			$result['missing'][] = $slug;
			continue;
		}

		$target = 'crane_category_' . $term->term_id;

		// اگر مدیر محتوا از قبل چیزی نوشته، دست نمی‌زنیم.
		$existing = get_field( 'seo_intro', $target );
		if ( ! empty( $existing ) ) {
			$result['skipped'][] = $slug;
			continue;
		}

		foreach ( $draft as $field => $value ) {
			update_field( $field, $value, $target );
		}

		$result['seeded'][] = $slug;
	}

	return $result;
}

