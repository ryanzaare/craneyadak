/**
 * پرامپت کاربر — داده‌ی مشخص همین محصول.
 * پرامپت سیستمی «چگونه بنویس» را می‌گوید؛ این یکی «درباره‌ی چه چیزی».
 */
function cyh_ai_user_prompt( $post_id ) {
	$title = get_the_title( $post_id );

	$brand_hint = '';
	$cat_hint   = '';
	$guess      = json_decode( (string) get_post_meta( $post_id, '_cyh_ai_guess', true ), true );
	if ( is_array( $guess ) ) {
		$brand_hint = $guess['brand'] ?? '';
		$cat_hint   = $guess['category'] ?? '';
	}

	$terms    = wp_get_post_terms( $post_id, 'crane_category', [ 'fields' => 'names' ] );
	$category = ( ! is_wp_error( $terms ) && ! empty( $terms ) ) ? $terms[0] : $cat_hint;

	// مشخصات از قبل ثبت‌شده (اگر کارشناس چیزی وارد کرده) — تنها داده‌ی
	// عددی مورد اعتماد. مدل باید از همین‌ها استفاده کند و بقیه را
	// [نیازمند بررسی فنی] بگذارد.
	$specs = '';
	if ( function_exists( 'get_field' ) ) {
		$rows = get_field( 'technical_specs', $post_id );
		if ( is_array( $rows ) ) {
			foreach ( $rows as $row ) {
				$label = isset( $row['spec_label'] ) ? trim( (string) $row['spec_label'] ) : '';
				$value = isset( $row['spec_value'] ) ? trim( (string) $row['spec_value'] ) : '';
				if ( $label && $value ) {
					$specs .= "  - {$label}: {$value}\n";
				}
			}
		}
	}

	$prompt  = "نام محصول: {$title}\n";
	if ( $category ) {
		$prompt .= "دسته‌بندی: {$category}\n";
	}
	if ( $brand_hint ) {
		$prompt .= "برند (حدس اولیه، تایید نشده): {$brand_hint}\n";
	}

	if ( $specs ) {
		$prompt .= "\nمشخصات فنیِ *تاییدشده* توسط کارشناس ما — فقط این اعداد قابل اتکا هستند:\n{$specs}";
		$prompt .= "هر عدد دیگری که لازم داشتی، [نیازمند بررسی فنی] بگذار.\n";
	} else {
		$prompt .= "\n⚠️ هیچ مشخصه‌ی فنی تاییدشده‌ای برای این محصول ثبت نشده است.\n";
		$prompt .= "بنابراین هر جا به عدد، ابعاد، ظرفیت یا کد نیاز شد، حتماً [نیازمند بررسی فنی] بنویس.\n";
	}

	$prompt .= "\nحالا «نمای کلی» و «بررسی تخصصی» را طبق دستورالعمل سیستمی بنویس.";
	$prompt .= "\nاگر ابزار جستجو در اختیار داری، ابتدا درباره‌ی این قطعه در منابع فارسی و بین‌المللی جستجو کن";
	$prompt .= " و فقط از اطلاعاتی استفاده کن که در نتایج جستجو دیده‌ای.";

	return $prompt;
}
